COMMENT ON COLUMN players.armor IS 'Nombre de coeurs bleus du personnage au départ';
COMMENT ON COLUMN players.black IS 'Nombre de coeurs noirs du personnage au départ';
COMMENT ON COLUMN players.coins IS 'Nombre de pièces du personnage au départ';
COMMENT ON COLUMN players.items IS 'Les items passifs ou actifs du personnage au départ';
COMMENT ON COLUMN players.bombs IS 'Nombre de bombes du personnage au départ';
COMMENT ON COLUMN players.card IS 'Les cartes du personnage au départ';
COMMENT ON COLUMN players.birthright IS 'Indique quel birthright est donné au personnage dans le jeu';
