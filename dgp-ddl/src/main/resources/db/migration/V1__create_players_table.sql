-- Script de création de la table Player
-- Projet : DGP (Dead God Project)

CREATE TABLE IF NOT EXISTS players (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- it_game : Identifiant technique du jeu (obligatoire)
    it_game BIGINT NOT NULL,

    -- name : nom du personnage (obligatoire)
    name VARCHAR(255) NOT NULL,

    -- skin : image.png de l'apparence du personnage
    skin VARCHAR(255) NOT NULL,

    -- stats vie (hp = coeurs rouges, armor = coeurs bleus, black = coeurs noirs)
    hp INTEGER NOT NULL DEFAULT 0,
    armor INTEGER DEFAULT 0,
    black INTEGER DEFAULT 0,

    -- Ressources en jeu
    coins INTEGER DEFAULT 0,
    items INTEGER DEFAULT 0,
    bombs INTEGER DEFAULT 0,
    card INTEGER,
    birthright VARCHAR(255),
    pocket_active INTEGER,

    -- Succès permettant de déploquer le personnage
    achievement INTEGER DEFAULT 0,

    -- Les skins et visuels
    costume INTEGER,
    skin_color INTEGER NOT NULL,
    costume_suffix VARCHAR(255),
    nameimage VARCHAR(255),
    portrait VARCHAR(255),

    -- Contraintes additionnelles pour la sécurité des données
    CONSTRAINT chk_hp_positive CHECK (hp >= 0),
    CONSTRAINT chk_coins_limit CHECK (coins >= 0 AND coins <= 99)
);

-- Commentaires sur la table
COMMENT ON TABLE players IS 'Table stockant les personnages jouables de The Binding of Isaac : Repentance';
COMMENT ON COLUMN players.it_game IS 'Id techniques des personnages après extraction des données de jeu';
